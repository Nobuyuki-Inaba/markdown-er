import { describe, expect, it } from 'vitest';
import { DdlDialect, DiagramModel, Table, createEmptyModel } from '../shared/DiagramModel';
import { DdlExporter } from '../src/ddl';
import { SqlImport, buildSqlImport } from '../webview/src/util/sqlImport/buildSqlImport';
import { shopModel, tableOf } from './fixtures';

const empty = () => createEmptyModel();

/** The import applied to an empty diagram, for exporting again */
function modelOf(result: SqlImport, base: DiagramModel): DiagramModel {
  return { ...base, tables: result.tables, relations: result.relations };
}

const run = (sql: string, dialect: DdlDialect = 'postgresql', model = empty()) => buildSqlImport(sql, model, dialect);
const tableIn = (result: SqlImport, name: string): Table => result.tables.find((t) => t.physicalName === name)!;
const columnIn = (result: SqlImport, table: string, name: string) => tableIn(result, table).columns.find((c) => c.physicalName === name)!;
const codes = (result: SqlImport) => result.warnings.map((w) => w.code);

describe('round trip: export, import, export', () => {
  const dialects: DdlDialect[] = ['mysql', 'postgresql', 'oracle', 'sqlserver', 'sqlite'];

  it.each(dialects)('%s gives the same DDL', (dialect) => {
    const model = shopModel();
    const ddl = DdlExporter.export(model, dialect, { comments: true });
    const result = run(ddl, dialect);
    expect(result.warnings).toEqual([]);
    expect(DdlExporter.export(modelOf(result, model), dialect, { comments: true })).toBe(ddl);
  });

  it.each(dialects)('%s keeps seed rows', (dialect) => {
    const model = shopModel();
    tableOf(model, 't_users').seedData = [
      { id: '1', name: "O'Brien", active: 'true' },
      { id: '2', name: '', active: 'false' },
    ];
    const options = { insertSeedData: true };
    const ddl = DdlExporter.export(model, dialect, options);
    const result = run(ddl, dialect);
    expect(result.warnings).toEqual([]);
    const rows = tableIn(result, 'users').seedData!;
    expect(rows.map((r) => r.name)).toEqual(["O'Brien", '']);
    expect(rows.map((r) => r.id)).toEqual(['1', '2']);
  });
});

describe('definitions', () => {
  it('reads columns, keys, defaults and comments', () => {
    const result = run(`
      CREATE TABLE IF NOT EXISTS shop.users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        email VARCHAR(255) NOT NULL UNIQUE,
        price NUMERIC(10, 2) DEFAULT 0 NOT NULL,
        status CHARACTER VARYING(20) DEFAULT 'new'::character varying,
        created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
        CHECK (price >= 0)
      );
      COMMENT ON TABLE users IS 'ユーザー: 利用者';
      COMMENT ON COLUMN shop.users.email IS 'メール';
    `);
    expect(result.warnings).toEqual([]);
    const users = tableIn(result, 'users');
    expect(users).toMatchObject({ logicalName: 'ユーザー', comment: '利用者' });
    expect(users.columns[0]).toMatchObject({ physicalName: 'id', isPrimaryKey: true, isNullable: false, autoIncrement: true, type: { dbType: 'BIGINT' } });
    expect(users.columns[1]).toMatchObject({ logicalName: 'メール', isNullable: false, type: { dbType: 'VARCHAR', length: 255 } });
    expect(users.columns[2]).toMatchObject({ defaultValue: '0', isNullable: false, type: { dbType: 'DECIMAL', length: 10, scale: 2 } });
    expect(users.columns[3]).toMatchObject({ defaultValue: "'new'::character varying", type: { dbType: 'VARCHAR', length: 20 } });
    expect(users.columns[4]).toMatchObject({ defaultValue: 'now()', isNullable: false, type: { dbType: 'TIMESTAMP' } });
    expect(users.constraints?.map((c) => [c.type, c.expression])).toEqual([['UNIQUE', 'email'], ['CHECK', 'price >= 0']]);
  });

  it('reads a mysqldump', () => {
    const result = run(`
      /*!40101 SET NAMES utf8mb4 */;
      DROP TABLE IF EXISTS \`orders\`;
      CREATE TABLE \`orders\` (
        \`id\` int(10) unsigned NOT NULL AUTO_INCREMENT COMMENT '注文ID',
        \`user_id\` int(10) unsigned NOT NULL,
        \`flag\` tinyint(1) NOT NULL DEFAULT '0',
        \`updated\` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
        \`key\` varchar(10) DEFAULT NULL,
        PRIMARY KEY (\`id\`),
        UNIQUE KEY \`uq_flag\` (\`flag\`) USING BTREE,
        KEY \`ix_user\` (\`user_id\`),
        CONSTRAINT \`fk_user\` FOREIGN KEY (\`user_id\`) REFERENCES \`users\` (\`id\`) ON DELETE CASCADE
      ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='注文';
      LOCK TABLES \`orders\` WRITE;
      INSERT INTO \`orders\` VALUES (1,2,0,'2020-01-01 00:00:00',NULL),(2,2,1,'it\\'s',"text");
      UNLOCK TABLES;
    `, 'mysql', { ...empty(), tables: [{ id: 't_u', logicalName: 'u', physicalName: 'users', comment: '', columns: [] }] });
    const orders = tableIn(result, 'orders');
    expect(orders.logicalName).toBe('注文');
    expect(orders.columns[0]).toMatchObject({ logicalName: '注文ID', isPrimaryKey: true, autoIncrement: true, type: { dbType: 'INT' } });
    expect(orders.columns[2]).toMatchObject({ defaultValue: "'0'", type: { dbType: 'BOOLEAN' } });
    expect(orders.columns[3].defaultValue).toBe('CURRENT_TIMESTAMP');
    expect(orders.columns[4]).toMatchObject({ physicalName: 'key', defaultValue: null, isNullable: true });
    expect(orders.indexes).toMatchObject([{ name: 'ix_user', columns: ['user_id'], unique: false }]);
    expect(orders.constraints).toMatchObject([{ type: 'UNIQUE', name: 'uq_flag', expression: 'flag' }]);
    expect(orders.seedData?.[1]).toMatchObject({ id: '2', updated: "it's", key: 'text' });
    expect(orders.seedData?.[0].key).toBe('');
  });

  it('reads a pg_dump, whose keys and sequences come after the table', () => {
    const result = run(`
      SET statement_timeout = 0;
      CREATE TABLE public.items (
          id integer NOT NULL,
          owner_id integer,
          tags text[],
          data jsonb DEFAULT '{}'::jsonb
      );
      ALTER TABLE public.items OWNER TO app;
      CREATE SEQUENCE public.items_id_seq START WITH 1;
      ALTER TABLE ONLY public.items ALTER COLUMN id SET DEFAULT nextval('public.items_id_seq'::regclass);
      CREATE TABLE public.owners (id integer NOT NULL);
      ALTER TABLE ONLY public.items ADD CONSTRAINT items_pkey PRIMARY KEY (id);
      ALTER TABLE ONLY public.owners ADD CONSTRAINT owners_pkey PRIMARY KEY (id);
      CREATE UNIQUE INDEX ix_owner ON public.items USING btree (owner_id);
      ALTER TABLE ONLY public.items ADD CONSTRAINT items_owner_fkey FOREIGN KEY (owner_id) REFERENCES public.owners(id);
      COPY public.items (id, owner_id) FROM stdin;
      1\tit's not SQL
      \\.
      SELECT pg_catalog.setval('public.items_id_seq', 1, true);
    `);
    expect(columnIn(result, 'items', 'id')).toMatchObject({ isPrimaryKey: true, autoIncrement: true, defaultValue: null });
    expect(columnIn(result, 'items', 'data')).toMatchObject({ defaultValue: "'{}'::jsonb", type: { dbType: 'JSON' } });
    expect(tableIn(result, 'items').indexes).toMatchObject([{ name: 'ix_owner', unique: true }]);
    expect(result.relations).toMatchObject([{ constraintName: 'items_owner_fkey', hasForeignKey: true, cardinality: 'ONE_TO_MANY' }]);
    expect(codes(result).sort()).toEqual(['copyUnsupported', 'typeApproximated']);
  });

  it('reads SQL Server scripts', () => {
    const result = run(`
      CREATE TABLE [dbo].[customers] (
        [id] INT IDENTITY(1,1) NOT NULL,
        [name] NVARCHAR(MAX) NULL,
        [rate] FLOAT NOT NULL,
        CONSTRAINT [PK_c] PRIMARY KEY CLUSTERED ([id] ASC)
      )
      GO
      INSERT [dbo].[customers] ([id], [name], [rate]) VALUES (1, N'佐藤', 1.5e-3)
      GO
    `, 'sqlserver');
    expect(columnIn(result, 'customers', 'id')).toMatchObject({ isPrimaryKey: true, autoIncrement: true });
    expect(columnIn(result, 'customers', 'name').type).toEqual({ dbType: 'TEXT', length: null });
    expect(columnIn(result, 'customers', 'rate').type).toEqual({ dbType: 'DOUBLE', length: null });
    expect(tableIn(result, 'customers').seedData).toEqual([{ id: '1', name: '佐藤', rate: '1.5e-3' }]);
  });

  it('does not make a plain integer key auto-increment', () => {
    const result = run('CREATE TABLE t (id INT PRIMARY KEY);');
    expect(columnIn(result, 't', 'id').autoIncrement).toBe(false);
  });

  it('keeps the first definition of a table declared twice', () => {
    const result = run('CREATE TABLE t (a INT); CREATE TABLE IF NOT EXISTS t (a INT, b INT);');
    expect(tableIn(result, 't').columns.map((c) => c.physicalName)).toEqual(['a']);
  });

  it('keeps a composite foreign key as logical relations', () => {
    const result = run(`
      CREATE TABLE p (a INT, b INT, PRIMARY KEY (a, b));
      CREATE TABLE c (id INT PRIMARY KEY, a INT, b INT, FOREIGN KEY (a, b) REFERENCES p);
    `);
    expect(result.relations).toHaveLength(2);
    expect(result.relations.every((r) => !r.hasForeignKey)).toBe(true);
    expect(codes(result)).toEqual(['compositeForeignKey']);
  });

  it('keeps foreign key actions in the relation comment', () => {
    const result = run(`
      CREATE TABLE p (id INT PRIMARY KEY);
      CREATE TABLE c (id INT PRIMARY KEY, p_id INT NOT NULL REFERENCES p ON DELETE SET NULL);
    `);
    expect(result.relations[0].comment).toBe('ON DELETE SET NULL');
    expect(columnIn(result, 'c', 'p_id').isNullable).toBe(false);
    expect(codes(result)).toEqual(['foreignKeyAction']);
  });

  it('marks a key that is the foreign key as one to one', () => {
    const result = run(`
      CREATE TABLE p (id INT PRIMARY KEY);
      CREATE TABLE c (id INT PRIMARY KEY REFERENCES p (id));
    `);
    expect(result.relations[0].cardinality).toBe('ONE_TO_ONE');
  });

  it('warns about what the diagram cannot hold', () => {
    const result = run(`
      CREATE TABLE t (
        a ENUM('x', 'y'),
        b INT GENERATED ALWAYS AS (1 + 1) STORED,
        c VARCHAR(10) AUTO_INCREMENT
      );
      CREATE INDEX ix_lower ON t (lower(c));
      CREATE VIEW v AS SELECT 1;
      UPDATE t SET a = 'x';
      ALTER TABLE t ADD CONSTRAINT fk FOREIGN KEY (a) REFERENCES missing (id);
    `, 'mysql');
    expect(codes(result).sort()).toEqual([
      'autoIncrementIgnored', 'computedColumn', 'foreignKeyUnresolved', 'indexExpression',
      'statementSkipped', 'statementSkipped', 'typeApproximated',
    ]);
  });

  it('ignores the body of a routine', () => {
    const result = run(`
      CREATE TABLE t (id INT PRIMARY KEY);
      CREATE TRIGGER tr AFTER INSERT ON t FOR EACH ROW
      BEGIN
        IF NEW.id > 0 THEN
          INSERT INTO t VALUES (99);
        END IF;
      END;
      INSERT INTO t VALUES (1);
    `, 'mysql');
    expect(tableIn(result, 't').seedData).toEqual([{ id: '1' }]);
  });

  it('survives broken input', () => {
    const result = run("CREATE TABLE ok (id INT);\nCREATE TABLE bad (;\nINSERT INTO ok VALUES ('never closed");
    expect(result.tables.map((t) => t.physicalName)).toEqual(['ok']);
    expect(tableIn(result, 'ok').columns).toHaveLength(1);
    expect(codes(result)).toContain('unterminatedString');
    expect(codes(result)).toContain('statementFailed');
  });
});

describe('importing into a diagram', () => {
  it('skips the definition of a table already there, whatever the case', () => {
    const model = shopModel();
    const result = buildSqlImport('CREATE TABLE USERS (x INT);', model, 'mysql');
    expect(result.tables).toEqual([]);
    expect(result.skippedTableNames).toEqual(['USERS']);
  });

  it('gives INSERT rows for an existing table, matching columns by name', () => {
    const model = shopModel();
    const result = buildSqlImport("INSERT INTO Users (NAME, id) VALUES ('a', 1), ('b', DEFAULT);", model, 'mysql');
    expect(result.existingSeedRows).toEqual([{
      tableId: 't_users',
      rows: [{ id: '1', name: 'a', active: '' }, { id: '', name: 'b', active: '' }],
    }]);
  });

  it('warns about rows that do not fit', () => {
    const model = shopModel();
    const result = buildSqlImport("INSERT INTO users VALUES (1); INSERT INTO users (nope) VALUES ('x'); INSERT INTO gone VALUES (1);", model, 'mysql');
    expect(codes(result).sort()).toEqual(['columnNotFound', 'rowSkipped', 'tableNotFound']);
  });

  it('keeps a value it cannot evaluate as text, with a warning', () => {
    const model = shopModel();
    const result = buildSqlImport("INSERT INTO users (id, name) VALUES (-1, UPPER('a'));", model, 'mysql');
    expect(result.existingSeedRows[0].rows[0]).toMatchObject({ id: '-1', name: "UPPER('a')" });
    expect(codes(result)).toEqual(['seedExpression']);
  });

  it('does not repeat a relation that exists', () => {
    const model = shopModel();
    const ddl = DdlExporter.export(model, 'postgresql');
    expect(buildSqlImport(ddl, model, 'postgresql').relations).toEqual([]);
  });

  it('adds a relation between existing tables', () => {
    const model = shopModel();
    model.relations = [];
    const result = buildSqlImport('ALTER TABLE orders ADD CONSTRAINT fk_x FOREIGN KEY (user_id) REFERENCES users (id);', model, 'mysql');
    expect(result.relations).toMatchObject([{ fromTableId: 't_users', toTableId: 't_orders', constraintName: 'fk_x' }]);
  });
});
