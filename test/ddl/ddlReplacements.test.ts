import { describe, expect, it } from 'vitest';
import { applyDdlReplacements, replacementPattern } from '../../shared/ddlReplacements';
import { DdlExporter } from '../../src/ddl/DdlExporter';
import { ErmdParser } from '../../src/ErmdParser';
import { ErmdSerializer } from '../../src/ErmdSerializer';
import { shopModel } from '../fixtures';

const uri = { path: '/work/shop.ermd' } as Parameters<typeof ErmdSerializer.serialize>[1];

describe('DDL replacements', () => {
  it('replaces literal text everywhere, $ included as is', () => {
    expect(applyDdlReplacements('a.b a.b', [{ id: '1', find: 'a.b', replace: '$x' }], 'mysql')).toBe('$x $x');
  });

  it('supports regular expressions with groups, per line', () => {
    const rules = [{ id: '1', find: '^(\\w+) INT$', replace: '$1 BIGINT', regex: true }];
    expect(applyDdlReplacements('id INT\nn INT', rules, 'mysql')).toBe('id BIGINT\nn BIGINT');
  });

  it('applies in order, only enabled rules for the dialect', () => {
    const rules = [
      { id: '1', find: 'A', replace: 'B' },
      { id: '2', find: 'B', replace: 'C' },
      { id: '3', find: 'C', replace: 'X', dialect: 'postgresql' as const },
      { id: '4', find: 'C', replace: 'Y', enabled: false },
    ];
    expect(applyDdlReplacements('A', rules, 'mysql')).toBe('C');
    expect(applyDdlReplacements('A', rules, 'postgresql')).toBe('X');
  });

  it('skips empty and invalid rules', () => {
    expect(replacementPattern({ find: '(', regex: true })).toBeNull();
    expect(replacementPattern({ find: '' })).toBeNull();
    expect(applyDdlReplacements('(x)', [{ id: '1', find: '(', replace: '', regex: true }], 'mysql')).toBe('(x)');
  });

  it('turns PostgreSQL identity columns into GENERATED ALWAYS', () => {
    const ddl = DdlExporter.export(shopModel(), 'postgresql');
    const out = applyDdlReplacements(ddl, [{ id: '1', find: 'GENERATED BY DEFAULT AS IDENTITY', replace: 'GENERATED ALWAYS AS IDENTITY' }], 'postgresql');
    expect(out).toContain('"id" INT GENERATED ALWAYS AS IDENTITY NOT NULL');
    expect(out).not.toContain('BY DEFAULT');
  });

  it('are saved in the diagram, leaving defaults out', () => {
    const model = shopModel();
    model.ddlReplacements = [{ id: 'r1', dialect: 'postgresql', find: 'a', replace: 'b', regex: true, enabled: false }, { id: 'r2', find: 'c', replace: 'd' }];
    const text = ErmdSerializer.serialize(model, uri);
    expect(text).toContain('```ermd-ddl-replacements');
    expect(text.match(/enabled:/g)).toHaveLength(1);
    expect(ErmdParser.parse(text).ddlReplacements).toEqual(model.ddlReplacements);
  });
});
