import { describe, expect, it } from 'vitest';
import { DdlExporter } from '../../src/ddl';
import { DdlDialect } from '../../shared/messages';
import { DdlStyle } from '../../shared/ddlStyle';
import { shopModel, tableOf } from '../fixtures';

const DIALECTS: DdlDialect[] = ['mysql', 'postgresql', 'oracle', 'sqlserver', 'sqlite'];

/** The CREATE TABLE statement for one table (optionally schema-qualified, quoted or not) */
function createOf(ddl: string, name: string): string {
  const start = ddl.search(new RegExp(`CREATE TABLE (\\S+\\.)?[\`"\\[]?${name}[\`"\\]]? \\(`));
  return ddl.slice(start, ddl.indexOf(';', start) + 1);
}

/** Every detail switched on */
const DETAILED: DdlStyle = { comments: true, tableOptions: true, explicitNull: true, quoteIdentifiers: true };

describe('DdlExporter', () => {
  it.each(DIALECTS)('%s: default (plain) DDL snapshot', (dialect) => {
    expect(DdlExporter.export(shopModel(), dialect, { insertSeedData: true })).toMatchSnapshot();
  });

  it.each(DIALECTS)('%s: detailed DDL snapshot', (dialect) => {
    expect(DdlExporter.export(shopModel(), dialect, { ...DETAILED, insertSeedData: true })).toMatchSnapshot();
  });

  describe('style', () => {
    it('is a plain CREATE TABLE by default: no comments, no table options, no explicit NULL', () => {
      const ddl = DdlExporter.export(shopModel(), 'mysql');
      expect(ddl).not.toMatch(/COMMENT|ENGINE|CHARSET/);
      expect(createOf(ddl, 'users').endsWith('\n);')).toBe(true);
      expect(createOf(ddl, 'profiles')).toContain('`bio` VARCHAR(100),');
    });

    it('quotes only where needed when quoteIdentifiers is off', () => {
      const model = shopModel();
      tableOf(model, 't_users').columns[1].physicalName = 'order';   // reserved word
      tableOf(model, 't_orders').columns[2].physicalName = 'Total';  // capital letter
      const mysql = DdlExporter.export(model, 'mysql', { quoteIdentifiers: false });
      expect(createOf(mysql, 'users')).toContain('id INT AUTO_INCREMENT NOT NULL');
      expect(createOf(mysql, 'users')).toContain('`order` VARCHAR(100) NOT NULL');
      expect(createOf(mysql, 'orders')).toContain('Total DECIMAL(10,2) NOT NULL');
      // PostgreSQL folds unquoted names to lower case, so capitals keep their quotes
      const pg = DdlExporter.export(model, 'postgresql', { quoteIdentifiers: false });
      expect(createOf(pg, 'orders')).toContain('"Total" DECIMAL(10,2) NOT NULL');
    });
  });

  describe('auto-increment', () => {
    it('applies only to a single integer PK that is not a foreign key', () => {
      const ddl = DdlExporter.export(shopModel(), 'mysql');
      expect(createOf(ddl, 'users')).toContain('`id` INT AUTO_INCREMENT NOT NULL');
      expect(createOf(ddl, 'orders')).toContain('AUTO_INCREMENT');
      // composite PK of a junction table
      expect(createOf(ddl, 'order_items')).not.toContain('AUTO_INCREMENT');
      // 1:1 child whose PK is the FK
      expect(createOf(ddl, 'profiles')).not.toContain('AUTO_INCREMENT');
    });

    it.each([
      ['postgresql', 'INT GENERATED BY DEFAULT AS IDENTITY', 'INT NOT NULL'],
      ['sqlserver', 'INT IDENTITY(1,1)', 'INT NOT NULL'],
    ] as const)('%s', (dialect, auto, plain) => {
      const ddl = DdlExporter.export(shopModel(), dialect);
      expect(createOf(ddl, 'users')).toContain(auto);
      expect(createOf(ddl, 'order_items')).not.toContain(auto);
      expect(createOf(ddl, 'order_items')).toContain(plain);
    });
  });

  it('declares PRIMARY KEY on every dialect, including SQLite', () => {
    for (const dialect of DIALECTS) {
      expect(createOf(DdlExporter.export(shopModel(), dialect), 'order_items')).toMatch(/PRIMARY KEY \(.?order_id.?, .?product_id.?\)/);
    }
  });

  describe('oracle', () => {
    it('maps types and leaves plain identifiers unquoted', () => {
      const ddl = DdlExporter.export(shopModel(), 'oracle');
      expect(createOf(ddl, 'users')).toContain('id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL');
      expect(createOf(ddl, 'users')).toContain('name VARCHAR2(100 CHAR) NOT NULL');
      expect(createOf(ddl, 'orders')).toContain('total NUMBER(10,2) NOT NULL');
    });

    it('quotes reserved words in upper case', () => {
      const model = shopModel();
      tableOf(model, 't_users').columns[1].physicalName = 'comment';
      expect(DdlExporter.export(model, 'oracle')).toContain('"COMMENT" VARCHAR2');
    });

    it('inserts one row per statement and resyncs the identity', () => {
      const model = shopModel();
      tableOf(model, 't_products').seedData = [{ id: '1' }, { id: '2' }];
      const out = DdlExporter.export(model, 'oracle', { insertSeedData: true });
      expect(out).toContain('INSERT INTO products (id) VALUES (1);\nINSERT INTO products (id) VALUES (2);');
      expect(out).toContain('ALTER TABLE products MODIFY (id GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH LIMIT VALUE));');
    });
  });

  describe('CREATE DATABASE / USER / SCHEMA', () => {
    function withDatabase() {
      const model = shopModel();
      model.database = {
        name: 'shop', schema: 'sales', user: 'app',
        options: {
          mysql: { collation: 'utf8mb4_ja_0900_as_cs' },
          postgresql: { collation: 'ja_JP.UTF-8', ctype: 'ja_JP.UTF-8' },
          sqlserver: { collation: 'Japanese_XJIS_140_CI_AS' },
        },
      };
      return model;
    }
    const head = (dialect: DdlDialect) =>
      DdlExporter.export(withDatabase(), dialect, { includeCreateDatabase: true }).split('\n\nCREATE TABLE')[0];

    it.each(DIALECTS)('%s snapshot', (dialect) => {
      expect(head(dialect)).toMatchSnapshot();
    });

    it('is omitted unless requested', () => {
      expect(DdlExporter.export(withDatabase(), 'mysql')).not.toContain('CREATE DATABASE');
    });

    it('MySQL tables follow the database charset / collation', () => {
      expect(createOf(DdlExporter.export(withDatabase(), 'mysql', { tableOptions: true }), 'users'))
        .toContain('ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_ja_0900_as_cs');
    });

    it('SQL Server qualifies tables with the schema', () => {
      const ddl = DdlExporter.export(withDatabase(), 'sqlserver');
      expect(ddl).toContain('CREATE TABLE [sales].[users] (');
      expect(ddl).toContain('REFERENCES [sales].[users] ([id])');
    });

    it("ignores another dialect's options", () => {
      expect(head('postgresql')).not.toContain('utf8mb4');
    });

    it('explains what is missing when nothing is set', () => {
      expect(DdlExporter.export(shopModel(), 'mysql', { includeCreateDatabase: true }))
        .toContain('-- MySQL: set a database name to generate CREATE DATABASE');
    });
  });

  it('makes primary key columns NOT NULL even when marked nullable', () => {
    const model = shopModel();
    tableOf(model, 't_products').columns[0].isNullable = true;
    expect(createOf(DdlExporter.export(model, 'mysql'), 'products')).toContain('NOT NULL');
  });

  it('SQLite: foreign keys are inline, there is no ALTER TABLE', () => {
    const ddl = DdlExporter.export(shopModel(), 'sqlite');
    expect(ddl).not.toContain('ALTER TABLE');
    expect(createOf(ddl, 'orders')).toContain('CONSTRAINT "fk_order_user" FOREIGN KEY ("user_id") REFERENCES "users" ("id")');
  });

  it('names an unnamed FK after its table and column', () => {
    expect(DdlExporter.export(shopModel(), 'mysql')).toContain('ADD CONSTRAINT `fk_order_items_product_id`');
  });

  it('keeps DECIMAL scale', () => {
    expect(createOf(DdlExporter.export(shopModel(), 'postgresql'), 'orders')).toContain('"total" DECIMAL(10,2)');
  });

  it('uses a column type given directly, without the dictionary', () => {
    const model = shopModel();
    const bio = tableOf(model, 't_profiles').columns[1];
    bio.dictionaryId = '';
    bio.type = { dbType: 'VARCHAR', length: 500 };
    expect(createOf(DdlExporter.export(model, 'postgresql'), 'profiles')).toContain('"bio" VARCHAR(500)');
    // The dictionary wins while it resolves
    bio.dictionaryId = 'd_name';
    expect(createOf(DdlExporter.export(model, 'postgresql'), 'profiles')).toContain('"bio" VARCHAR(100)');
  });

  it('writes logical names and comments as column comments when comments are on', () => {
    const mysql = DdlExporter.export(shopModel(), 'mysql', { comments: true });
    expect(mysql).toContain("COMMENT 'ユーザー名: display name, can''t be empty'");
    expect(mysql).toContain("COMMENT='ユーザー'");
    const pg = DdlExporter.export(shopModel(), 'postgresql', { comments: true });
    expect(pg).toContain(`COMMENT ON COLUMN "users"."name" IS 'ユーザー名: display name, can''t be empty';`);
    expect(pg).toContain(`COMMENT ON TABLE "users" IS 'ユーザー';`);
  });

  describe('seed data', () => {
    function withSeeds() {
      const model = shopModel();
      tableOf(model, 't_orders').seedData = [{ id: '1', user_id: '1', total: '9.99' }];
      tableOf(model, 't_users').seedData = [{ id: '1', name: "O'Brien", active: 'true' }];
      return model;
    }

    it('inserts parent tables before children', () => {
      const ddl = DdlExporter.export(withSeeds(), 'mysql', { insertSeedData: true });
      expect(ddl.indexOf('INSERT INTO `users`')).toBeLessThan(ddl.indexOf('INSERT INTO `orders`'));
    });

    it('escapes strings and maps booleans per dialect', () => {
      expect(DdlExporter.export(withSeeds(), 'postgresql', { insertSeedData: true })).toContain(`(1, 'O''Brien', TRUE)`);
      expect(DdlExporter.export(withSeeds(), 'mysql', { insertSeedData: true })).toContain(`(1, 'O''Brien', 1)`);
    });

    it('PostgreSQL advances the identity sequence after explicit ids', () => {
      expect(DdlExporter.export(withSeeds(), 'postgresql', { insertSeedData: true }))
        .toContain(`SELECT setval(pg_get_serial_sequence('"users"', 'id'), (SELECT MAX("id") FROM "users"));`);
      expect(DdlExporter.export(withSeeds(), 'postgresql', { insertSeedData: true, skipAutoIncrementPk: true }))
        .not.toContain('setval');
    });

    it('SQL Server wraps explicit identity values, unless the PK is skipped', () => {
      expect(DdlExporter.export(withSeeds(), 'sqlserver', { insertSeedData: true })).toContain('SET IDENTITY_INSERT [users] ON;');
      const skipped = DdlExporter.export(withSeeds(), 'sqlserver', { insertSeedData: true, skipAutoIncrementPk: true });
      expect(skipped).not.toContain('IDENTITY_INSERT');
      expect(skipped).toContain('INSERT INTO [users] ([name], [active])');
    });
  });
});
