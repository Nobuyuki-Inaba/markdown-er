import { Column, DictionaryEntry, Table, typeSizeSuffix } from '../../../shared/DiagramModel';
import { ColumnChange, SqlDialect, commentText } from '../SqlDialect';
import type { Schema } from '../Schema';

const IDENTITY = 'GENERATED BY DEFAULT ON NULL AS IDENTITY';
const SIMPLE_IDENTIFIER = /^[A-Za-z][A-Za-z0-9_$#]*$/;
/** Reserved words that are common column / table names */
const RESERVED = new Set([
  'ACCESS', 'AUDIT', 'COMMENT', 'DATE', 'FILE', 'GROUP', 'INDEX', 'LEVEL', 'MODE', 'NUMBER', 'ORDER',
  'RESOURCE', 'ROW', 'ROWS', 'SESSION', 'SIZE', 'START', 'TABLE', 'UID', 'USER', 'VALUES', 'VIEW',
]);

/**
 * Oracle Database 12c+ (identity columns). In Oracle a schema is a user, and the
 * character set is fixed when the database itself is created.
 */
export class OracleDialect extends SqlDialect {
  readonly id = 'oracle';
  readonly label = 'Oracle';

  /**
   * Plain identifiers stay unquoted: Oracle folds them to upper case, so they can be
   * referenced without quotes later. Quoting would make them case-sensitive.
   */
  quote(name: string): string {
    if (SIMPLE_IDENTIFIER.test(name)) {
      return RESERVED.has(name.toUpperCase()) ? `"${name.toUpperCase()}"` : name;
    }
    return `"${name.replace(/"/g, '""')}"`;
  }

  protected defaultType(): string {
    return 'VARCHAR2(255 CHAR)';
  }

  protected mapType(entry: DictionaryEntry, autoIncrement: boolean): string {
    const len = entry.length;
    switch (entry.dbType) {
      case 'INT':       return autoIncrement ? `NUMBER(10) ${IDENTITY}` : 'NUMBER(10)';
      case 'BIGINT':    return autoIncrement ? `NUMBER(19) ${IDENTITY}` : 'NUMBER(19)';
      case 'SMALLINT':  return 'NUMBER(5)';
      case 'TINYINT':   return 'NUMBER(3)';
      case 'BOOLEAN':   return 'NUMBER(1)';
      case 'DECIMAL':   return `NUMBER${typeSizeSuffix(entry)}`;
      case 'FLOAT':     return 'BINARY_FLOAT';
      case 'DOUBLE':    return 'BINARY_DOUBLE';
      case 'VARCHAR':   return `VARCHAR2(${len ?? 255} CHAR)`;
      case 'CHAR':      return `CHAR(${len ?? 1} CHAR)`;
      case 'TEXT':
      case 'LONGTEXT':
      case 'JSON':      return 'CLOB';
      case 'DATETIME':
      case 'TIMESTAMP': return 'TIMESTAMP';
      case 'DATE':      return 'DATE';
      case 'TIME':      return 'INTERVAL DAY(0) TO SECOND(0)';
      case 'BLOB':      return 'BLOB';
    }
  }

  /** The schema owner is a user; its name is the schema (or user, or database) name */
  createDatabase(): string[] {
    const owner = this.schemaName || this.userName || this.databaseName;
    if (!owner) { return [this.note('set a schema or user name to generate CREATE USER')]; }
    const o = this.quote(owner);
    const { collation } = this.databaseOptions();
    return [
      this.note('the character set (e.g. AL32UTF8) is chosen when the database itself is created'),
      this.changePasswordNote(),
      `CREATE USER ${o} IDENTIFIED BY "${this.passwordPlaceholder}"` +
        `${collation ? ` DEFAULT COLLATION ${collation}` : ''} QUOTA UNLIMITED ON USERS;`,
      `GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW TO ${o};`,
      `ALTER SESSION SET CURRENT_SCHEMA = ${o};`,
    ];
  }

  commentStatements(table: Table, columns: Column[], includeTable: boolean): string[] {
    return this.commentOnStatements(table, columns, includeTable);
  }

  changeTableComment(table: Table, comment: string): string[] {
    return [this.commentOnTable(table, comment)];
  }

  /** Multi-row VALUES needs 23ai; one INSERT per row works everywhere */
  insertStatement(table: Table, columns: Column[], rows: string[]): string {
    const cols = columns.map((c) => this.quote(c.physicalName)).join(', ');
    return rows.map((r) => `INSERT INTO ${this.table(table.physicalName)} (${cols}) VALUES ${r};`).join('\n');
  }

  /** Move the identity past the explicit ids so later INSERTs don't collide */
  wrapExplicitIdentityInsert(table: Table, identity: Column, insert: string): string {
    return (
      `${insert}\n` +
      `ALTER TABLE ${this.table(table.physicalName)} MODIFY (${this.quote(identity.physicalName)} ${IDENTITY} (START WITH LIMIT VALUE));`
    );
  }

  /** IF EXISTS needs 23ai */
  dropTable(table: Table): string {
    return `DROP TABLE ${this.table(table.physicalName)} CASCADE CONSTRAINTS;`;
  }

  addColumn(table: Table, col: Column, schema: Schema): string[] {
    return [
      `ALTER TABLE ${this.table(table.physicalName)} ADD (${this.columnDefinition(col, schema)});`,
      ...this.commentStatements(table, [col], false),
    ];
  }

  /** MODIFY only what changed: restating NOT NULL on a NOT NULL column is an error (ORA-01442) */
  alterColumn(ch: ColumnChange): string[] {
    const parts: string[] = [];
    if (ch.typeChanged)    { parts.push(ch.newType); }
    if (ch.defaultChanged) { parts.push(`DEFAULT ${ch.newDefault ?? 'NULL'}`); }
    if (ch.nullChanged)    { parts.push(ch.notNull ? 'NOT NULL' : 'NULL'); }

    const stmts: string[] = [];
    if (parts.length > 0) {
      stmts.push(`ALTER TABLE ${this.table(ch.table.physicalName)} MODIFY (${this.quote(ch.after.physicalName)} ${parts.join(' ')});`);
    }
    if (ch.commentChanged) {
      stmts.push(this.commentOnColumn(ch.table, ch.after, commentText(ch.after)));
    }
    if (ch.autoIncrementChanged) {
      stmts.push(this.note(`identity of ${ch.table.physicalName}.${ch.after.physicalName} cannot be added or removed; recreate the column`));
    }
    return stmts;
  }

  changePrimaryKey(before: Table, after: Table): string[] {
    const t = this.table(after.physicalName);
    const stmts: string[] = [];
    if (before.columns.some((c) => c.isPrimaryKey)) { stmts.push(`ALTER TABLE ${t} DROP PRIMARY KEY;`); }
    const add = this.primaryKeyClause(after);
    if (add) { stmts.push(`ALTER TABLE ${t} ADD ${add};`); }
    return stmts;
  }
}
