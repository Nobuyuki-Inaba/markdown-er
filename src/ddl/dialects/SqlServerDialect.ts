import { Column, DictionaryEntry, Table, TableIndex, typeSizeSuffix } from '../../../shared/DiagramModel';
import { ColumnChange, SqlDialect } from '../SqlDialect';
import type { Schema } from '../Schema';

export class SqlServerDialect extends SqlDialect {
  readonly id = 'sqlserver';
  readonly label = 'SQL Server';

  quote(name: string): string {
    return `[${name.replace(/]/g, ']]')}]`;
  }

  protected defaultType(): string {
    return 'NVARCHAR(255)';
  }

  protected mapType(entry: DictionaryEntry, autoIncrement: boolean): string {
    const size = typeSizeSuffix(entry);
    switch (entry.dbType) {
      case 'INT':
      case 'BIGINT':    return autoIncrement ? `${entry.dbType} IDENTITY(1,1)` : entry.dbType;
      case 'BOOLEAN':   return 'BIT';
      // SQL Server TIMESTAMP is a row version, not a date/time
      case 'DATETIME':
      case 'TIMESTAMP': return 'DATETIME2';
      case 'VARCHAR':   return `NVARCHAR${size || '(255)'}`;
      case 'CHAR':      return `NCHAR${size}`;
      case 'TEXT':
      case 'LONGTEXT':
      case 'JSON':      return 'NVARCHAR(MAX)';
      case 'BLOB':      return 'VARBINARY(MAX)';
      case 'DOUBLE':    return 'FLOAT';
      default:          return this.sized(entry);
    }
  }

  wrapExplicitIdentityInsert(table: Table, insert: string): string {
    const t = this.quote(table.physicalName);
    return `SET IDENTITY_INSERT ${t} ON;\n${insert}\nSET IDENTITY_INSERT ${t} OFF;`;
  }

  renameTable(from: string, to: string): string {
    return `EXEC sp_rename ${this.string(from)}, ${this.string(to)};`;
  }

  renameColumn(table: Table, from: string, to: string): string {
    return `EXEC sp_rename ${this.string(`${table.physicalName}.${from}`)}, ${this.string(to)}, 'COLUMN';`;
  }

  addColumn(table: Table, col: Column, schema: Schema): string[] {
    return [`ALTER TABLE ${this.quote(table.physicalName)} ADD ${this.columnDefinition(col, schema)};`];
  }

  dropIndex(table: Table, idx: TableIndex): string {
    return `DROP INDEX ${this.quote(idx.name)} ON ${this.quote(table.physicalName)};`;
  }

  alterColumn(ch: ColumnChange): string[] {
    const where = `${ch.table.physicalName}.${ch.after.physicalName}`;
    const stmts: string[] = [];
    if (ch.typeChanged || ch.nullChanged) {
      stmts.push(
        `ALTER TABLE ${this.quote(ch.table.physicalName)} ALTER COLUMN ${this.quote(ch.after.physicalName)} ` +
        `${ch.newType} ${ch.notNull ? 'NOT NULL' : 'NULL'};`
      );
    }
    if (ch.defaultChanged)       { stmts.push(this.note(`change the DEFAULT constraint of ${where} manually`)); }
    if (ch.autoIncrementChanged) { stmts.push(this.note(`IDENTITY of ${where} cannot be altered; recreate the column`)); }
    return stmts;
  }

  changePrimaryKey(before: Table, after: Table): string[] {
    const stmts: string[] = [];
    if (before.columns.some((c) => c.isPrimaryKey)) {
      // The PK constraint name is generated by SQL Server
      stmts.push(this.note(`drop the existing PRIMARY KEY constraint of ${after.physicalName} manually`));
    }
    const add = this.primaryKeyClause(after);
    if (add) { stmts.push(`ALTER TABLE ${this.quote(after.physicalName)} ADD ${add};`); }
    return stmts;
  }
}
